# @title
import os
import sys
import nltk
from nltk.stem import WordNetLemmatizer

# Ensure required NLTK data is downloaded
nltk.download('wordnet', quiet=True)
nltk.download('omw-1.4', quiet=True)

def load_coca_dictionary(filepath="/content/COCA_20000.txt"):
    """
    Loads the authentic COCA vocabulary list from the specified local path.
    Expected format: One purely English word per line.
    """
    vocab = set()
    if os.path.exists(filepath):
        print(f"[Info] Loading COCA vocabulary from {filepath}...")
        with open(filepath, 'r', encoding='utf-8') as f:
            for line in f:
                word = line.strip().lower()
                if word:
                    vocab.add(word)
        print("[Info] Successfully loaded COCA 20,000 high-frequency words.")
        return vocab
    else:
        print(f"[Error] File not found at '{filepath}'.")
        print("[Error] Please ensure the COCA dictionary file is uploaded to the correct path.")
        sys.exit(1)

def classify_transparency(toponym, vocab_set):
    """
    Classifies a toponym's transparency based on whether its morphological
    constituents (or their lemmas) exist in the COCA high-frequency vocabulary.
    Returns: (Classification, Left Part, Right Part)
    """
    clean_name = toponym.lower().strip()
    lemmatizer = WordNetLemmatizer()

    # Helper to check if word exists or has a valid lemma in vocab
    def is_valid_word(word):
        # Check exact match, noun lemma, and verb lemma
        if word in vocab_set: return True
        if lemmatizer.lemmatize(word, pos='n') in vocab_set: return True
        if lemmatizer.lemmatize(word, pos='v') in vocab_set: return True
        return False

    # Iterate through all possible split indices
    for i in range(1, len(clean_name)):
        left_part = clean_name[:i]
        right_part = clean_name[i:]

        # New restriction: each part must have at least 2 characters
        if len(left_part) > 1 and len(right_part) > 1:
            if is_valid_word(left_part) and is_valid_word(right_part):
                return "Transparent", left_part, right_part

    return "Opaque", None, None

def interactive_mode():
    print("=" * 55)
    print("   Toponym Transparency Classifier (COCA Edition)   ")
    print("=" * 55)

    # Load the dictionary
    vocab = load_coca_dictionary("/content/COCA_20000.txt")
    print("-" * 55)

    # Start the interactive loop
    while True:
        user_input = input("\nEnter a toponym to test (type 'q' to quit): ").strip()

        if user_input.lower() in ['quit', 'q', 'exit']:
            print("Exiting classifier. Good luck with your experiment!")
            break

        if not user_input:
            continue

        if " " in user_input:
            print(f"[Note] '{user_input}' contains a space. This tool is designed for single-word compounds.")
            continue

        classification, left, right = classify_transparency(user_input, vocab)

        if classification == "Transparent":
            print(f"✅ [Result] '{user_input}' is classified as: TRANSPARENT")
            print(f"   [Reason] Successfully split into two COCA words: '{left}' + '{right}'")
        else:
            print(f"❌ [Result] '{user_input}' is classified as: OPAQUE")
            print(f"   [Reason] Cannot be split into two valid constituents (length > 1) from the COCA dictionary.")

if __name__ == "__main__":
    interactive_mode()

