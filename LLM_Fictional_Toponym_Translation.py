from openai import OpenAI

client = OpenAI(
    api_key="Enter Your LLM API Here")

import csv

# Experiment metadata (modify when running different experiments)
experiment_id = "Exp0"
familiarity = "Existing"       # Existing / Coined
transparency = "Transparent"   # Transparent / Opaque
context = "Zero"   # Zero / Original / Constructed


# Store results
results = []


while True:
    toponym = input("\nEnter a toponym (type 'q' to quit): ").strip()

    if toponym.lower() in ["q", "quit", "exit"]:
        print("Experiment stopped.")
        break

    if not toponym:
        continue


    prompt = f"""
Translate the following toponym "{toponym}" into Chinese.

Provide only one translation.

Do not rely on existing translations or external references.

After providing the translation, briefly explain the rationale and strategy used when translating the toponym.
"""


    response = client.responses.create(
        model="gpt-5.4-mini",
        input=prompt,
        store=False,
        temperature=0
    )


    output = response.output_text


    print("\n--- Output ---")
    print(output)
    print("-" * 50)


    # Save result
    results.append({
        "Experiment": experiment_id,
        "Toponym": toponym,
        "Familiarity": familiarity,
        "Transparency": transparency,
        "Context": context,
        "Output": output
    })


# Export results to CSV
filename = f"{experiment_id}_{familiarity}_{transparency}_{context}.csv"

with open(filename, "w", newline="", encoding="utf-8-sig") as f:
    writer = csv.DictWriter(
        f,
        fieldnames=[
            "Experiment",
            "Toponym",
            "Familiarity",
            "Transparency",
            "Context",
            "Output"
        ]
    )

    writer.writeheader()
    writer.writerows(results)


print(f"\nResults saved as: {filename}")